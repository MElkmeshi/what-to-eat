// First matching keyword wins, so more specific dishes come first
// (e.g. طاجين هامبورقا is a tajine, رز ودجاج is a rice dish).
const RULES: [string[], string][] = [
  [['بيتزا'], '🍕'],
  [['طاجين', 'قلايا'], '🥘'],
  [['هامبورقا', 'برقر', 'برجر'], '🍔'],
  [['مكرونة', 'معكرونة', 'الفريدو', 'لازانيا', 'كاريلوني', 'رشدة', 'شعيرية', 'سباقيتي'], '🍝'],
  [['كسكسي', 'فاصولياء', 'بازلياء', 'عصبان', 'شربة', 'بازين'], '🍲'],
  [['رز', 'مقلوبة', 'مكبوسة'], '🍛'],
  [['شاورما', 'ملفوفة'], '🌯'],
  [['كنتاكي', 'دجاج', 'فراخ'], '🍗'],
  [['كفتة', 'كباب', 'مشوي'], '🍢'],
  [['مبطن', 'بطاطا', 'بطاطس'], '🥔'],
  [['بوريك', 'سمبوسة'], '🥟'],
  [['سندويش', 'ساندويتش'], '🥪'],
  [['سمك', 'حوت'], '🐟'],
  [['سلطة'], '🥗'],
]

export function emojiFor(name: string) {
  return RULES.find(([words]) => words.some((w) => name.includes(w)))?.[1] ?? '🍽️'
}
